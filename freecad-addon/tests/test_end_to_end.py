# --- Makera Carvera 4-axis end-to-end ---

class TestCarvera4AxisEndToEnd:
    def test_rotary_plan_and_validate(self):
        setup = RotaryJobSetup(
            stock_diameter_mm=50,
            stock_length_mm=100,
            strategy=RotaryStrategy.ROUGHING,
            a_step_deg=45,
            stepdown_mm=1.0,
            spindle_rpm=10000,
        )
        op = plan_operation(setup, depth_mm=3.0)
        gcode = operation_to_gcode(op)
        assert "G21" in gcode
        assert "M2" in gcode
        assert "G0 Y0" in gcode
        assert "G0 A0" in gcode

    def test_rotary_collision_check_safe(self):
        fixture = RotaryFixture(chuck_outer_radius_mm=46)
        segments = [
            (50, 0, 30),
            (100, 0, 30),
            (150, 0, 30),
        ]
        result = sweep_segments(segments, tool_radius=3.175, fixture=fixture)
        assert not result.has_collision

    def test_rotary_collision_check_collision(self):
        fixture = RotaryFixture(chuck_outer_radius_mm=46)
        segments = [
            (5, 0, 40),
            (5, 0, 50),
        ]
        result = sweep_segments(segments, tool_radius=3.175, fixture=fixture)
        assert result.has_collision

    def test_all_strategies_produce_gcode(self):
        for strategy in RotaryStrategy:
            setup = RotaryJobSetup(
                stock_diameter_mm=50,
                stock_length_mm=100,
                strategy=strategy,
            )
            op = plan_operation(setup, 2.0)
            gcode = operation_to_gcode(op)
            assert len(gcode) > 0
            assert "G21" in gcode


# --- K2 Plus end-to-end ---

class TestK2PlusEndToEnd:
    K2_GCODE = """\
; Generated by WorkTrackCAM for Creality K2 Plus
M104 S210
M140 S60
M109 S210
M190 S60
G28
G1 Z5 F3000
G1 X0.1 Y20 F5000
G1 X0.1 Y200 E15 F1500
M104 S0
M140 S0
M84
"""

    def test_validation_passes(self):
        result = validate_post_output(self.K2_GCODE, "Creality_K2_Plus")
        assert result.passed

    def test_temp_validation_catches_overtemp(self):
        bad_gcode = self.K2_GCODE.replace("M104 S210", "M104 S400")
        violations = validate_gcode_temps(bad_gcode, TempCeilings(max_nozzle_c=350))
        assert len(violations) == 1
        assert violations[0].component == "nozzle"

    def test_k2_presets_are_within_ceilings(self):
        ceilings = TempCeilings(max_nozzle_c=350, max_bed_c=120)
        for name, preset in PRESETS.items():
            assert preset.nozzle_temp_c <= ceilings.max_nozzle_c, f"{name} nozzle too hot"
            assert preset.bed_temp_c <= ceilings.max_bed_c, f"{name} bed too hot"

    def test_k2_start_gcode_validates(self):
        gcode = get_k2_start_gcode("standard") + "\n" + get_k2_end_gcode()
        violations = validate_gcode_temps(gcode, TempCeilings())
        assert len(violations) == 0


# --- Machine profile integrity ---

class TestMachineProfileIntegrity:
    def test_all_fcm_files_are_valid_json(self):
        machines_dir = ADDON_ROOT / "machines"
        for fcm_file in machines_dir.glob("*.fcm"):
            with open(fcm_file) as f:
                data = json.load(f)
            assert "name" in data, f"{fcm_file.name} missing name"
            has_axes = "axes" in data or "linear_axes" in data
            assert has_axes, f"{fcm_file.name} missing axes or linear_axes"

    def test_all_machines_have_validation_dialects(self):
        machines_dir = ADDON_ROOT / "machines"
        for fcm_file in machines_dir.glob("*.fcm"):
            machine_id = fcm_file.stem
            assert machine_id in MACHINE_DIALECTS, f"{machine_id} missing from MACHINE_DIALECTS"

    def test_post_processor_files_exist(self):
        posts_dir = ADDON_ROOT / "posts"
        expected = [
            "richauto_a_series.py",
            "makera_carvera.py",
            "makera_carvera_4axis.py",
            "klipper_moonraker.py",
        ]
        for name in expected:
            assert (posts_dir / name).exists(), f"Missing post-processor: {name}"

    def test_addon_package_xml_exists(self):
        assert (ADDON_ROOT / "package.xml").exists()

    def test_init_files_exist(self):
        assert (ADDON_ROOT / "Init.py").exists()
        assert (ADDON_ROOT / "InitGui.py").exists()
