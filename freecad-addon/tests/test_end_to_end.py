# --- Laguna Swift 5x10 end-to-end ---

class TestLagunaEndToEnd:
    LAGUNA_GCODE = """\
%
; VCarve Pro post — Laguna Swift 5x10
G21
G90
G17
G94
G0 Z203.0
M3 S18000
G4 P2.0
M7
G0 X50.0 Y50.0
G1 Z-5.0 F1000
G1 X150.0 Y50.0 F2000
G1 X150.0 Y150.0
G0 Z25.0
M9
M5
G4 P3.0
G0 Z203.0
G0 X0 Y0
M30
%
"""

    def test_full_sheet_workflow(self):
        allocations = allocate_zones(0, 0, *SHEET_PRESETS["full_4x8"])
        engaged = engaged_zone_indices(allocations)
        assert len(engaged) > 0

        wrapped = wrap_gcode_with_vacuum(self.LAGUNA_GCODE, engaged)
        assert "M64" in wrapped
        assert "M65" in wrapped

        result = validate_post_output(self.LAGUNA_GCODE, "Laguna_Swift_5x10")
        assert result.passed

    def test_half_sheet_engages_fewer_zones(self):
        full_alloc = allocate_zones(0, 0, *SHEET_PRESETS["full_4x8"])
        half_alloc = allocate_zones(0, 0, *SHEET_PRESETS["half_4x4"])
        full_engaged = engaged_zone_indices(full_alloc)
        half_engaged = engaged_zone_indices(half_alloc)
        assert len(half_engaged) <= len(full_engaged)


