class TestK2PlusFDMPattern:
    def test_nozzle_temp(self):
        assert "M104 S210" in K2_PLUS_GCODE

    def test_bed_temp(self):
        assert "M140 S60" in K2_PLUS_GCODE

    def test_temps_within_ceiling(self):
        result = validate_post_output(K2_PLUS_GCODE, "Creality_K2_Plus")
        assert len(result.temp_violations) == 0

    def test_over_ceiling_detected(self):
        bad_gcode = K2_PLUS_GCODE.replace("M104 S210", "M104 S400")
        result = validate_post_output(bad_gcode, "Creality_K2_Plus")
        assert not result.passed
        assert len(result.temp_violations) == 1


class TestValidationPipeline:
    def test_unknown_machine_fails(self):
        result = validate_post_output("G0 X0", "NonExistent_Machine")
        assert not result.passed

    def test_all_machines_have_dialects(self):
        expected = ["Laguna_Swift_5x10", "Makera_Carvera_3axis", "Makera_Carvera_4axis", "Creality_K2_Plus"]
        for machine_id in expected:
            assert machine_id in MACHINE_DIALECTS

    def test_laguna_dialect_is_mach3(self):
        assert MACHINE_DIALECTS["Laguna_Swift_5x10"].dialect == "mach3"

    def test_carvera_dialect_is_grbl(self):
        assert MACHINE_DIALECTS["Makera_Carvera_3axis"].dialect == "grbl"
        assert MACHINE_DIALECTS["Makera_Carvera_4axis"].dialect == "grbl"
