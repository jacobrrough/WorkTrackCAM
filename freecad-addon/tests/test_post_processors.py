class TestLagunaPostPattern:
    def test_has_tape_markers(self):
        lines = LAGUNA_GCODE.strip().splitlines()
        assert lines[0] == "%"
        assert lines[-1] == "%"

    def test_has_units_mode_plane(self):
        assert "G21" in LAGUNA_GCODE
        assert "G90" in LAGUNA_GCODE
        assert "G17" in LAGUNA_GCODE
        assert "G94" in LAGUNA_GCODE

    def test_spindle_warmup_dwell(self):
        assert "M3 S18000" in LAGUNA_GCODE
        assert "G4 P2.0" in LAGUNA_GCODE

    def test_dust_collection(self):
        lines = LAGUNA_GCODE.splitlines()
        m7_idx = next(i for i, l in enumerate(lines) if "M7" in l)
        m9_idx = next(i for i, l in enumerate(lines) if "M9" in l)
        assert m7_idx < m9_idx

    def test_spindle_cooldown_ramp(self):
        assert "M5" in LAGUNA_GCODE
        assert "G4 P3.0" in LAGUNA_GCODE

    def test_m30_end(self):
        assert "M30" in LAGUNA_GCODE

    def test_safe_z_retract(self):
        assert "G0 Z203.0" in LAGUNA_GCODE

    def test_passes_validation(self):
        result = validate_post_output(LAGUNA_GCODE, "Laguna_Swift_5x10")
        assert result.passed, f"Validation failed: {result.all_violations}"


