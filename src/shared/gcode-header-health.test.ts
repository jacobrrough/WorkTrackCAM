/**
 * Tests for `gcode-header-health.ts` -- the pure parser used by
 * `moonraker-push.ts` to surface advisory K2 Plus header diagnostics
 * (estimated time, filament use, layer count, embedded thumbnail PNG,
 * Klipper power-loss recovery sentinel, adaptive-probing sentinel).
 *
 * Quick-win bundle (undo/redo + K2 thumbnail + Klipper header).
 */
import { describe, expect, it } from 'vitest'
import {
  checkGcodeHeaderHealth,
  hasAdaptiveProbingHeader,
  hasPowerLossRecoveryHeader,
  hasThumbnailBlock,
} from './gcode-header-health'

