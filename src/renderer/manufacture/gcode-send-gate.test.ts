/**
 * gcode-send-gate.test.ts -- Wave 3m behavioral contract for the LIVE
 * send/export safety seam (`gcode-send-gate.ts`).
 *
 * Every test runs the REAL surface action the production button invokes,
 * with the IPC boundary mocked (`window.fab.*` equivalents injected as
 * spies) and the machine dims loaded from the REAL bundled profiles in
 * `resources/machines/*.json` -- so a profile-dim regression or a seam
 * regression both surface here:
 *   - Laguna Swift 5x10  : 1524 x 3048 mm (mach3, safeRetractZMm 25)
 *   - Carvera 3-axis     : 360 x 240 mm   (smoothieware, retract = z 140)
 *   - Carvera 4th-axis   : 240 x 92 mm    (grbl_4axis,  retract = z 46)
 *   - K2 Plus (FDM)      : dims NEVER passed -- advisory-only by contract
 *
 * The blocking paths assert BOTH halves of the safety contract: the
 * dispatch IPC is never invoked AND the honest message reaches the
 * operator via onStatus. The K2 section asserts the inverse: the push can
 * NEVER be blocked by this seam (the main-process temperature validator in
 * moonraker-push.ts -- untouched by Wave 3m -- remains the K2's hard gate).
 */
import { describe, expect, it, vi } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import {
  adviseFdmProgramForPush,
  formatBlockedSendStatus,
  formatSendAdvisoriesStatus,
  formatSetupSheetGateNotice,
  gateCncProgramForSend,
  gateSafeRetractZMm,
  runCarveraUploadSurface,
  runGatedCncSendFlow,
  runK2PushSurface,
  runLagunaExportSurface,
  type GateIo,
  type GateMachine,
  type K2PushMachine
} from './gcode-send-gate'

// --- Real bundled profiles (resources/machines/*.json) ----------------------

const MACHINES_DIR = resolve(__dirname, '..', '..', '..', 'resources', 'machines')

type BundledGateProfile = GateMachine & { readonly id: string; readonly kind: string }

function readBundledProfile(file: string): BundledGateProfile {
  return JSON.parse(readFileSync(resolve(MACHINES_DIR, file), 'utf-8')) as BundledGateProfile
}

const LAGUNA = readBundledProfile('laguna-swift-5x10.json')
const CARVERA3 = readBundledProfile('makera-carvera-3axis.json')
const CARVERA4 = readBundledProfile('makera-carvera-4axis.json')
const K2_PLUS = readBundledProfile('creality-k2-plus.json') as BundledGateProfile & K2PushMachine

// --- Program fixtures --------------------------------------------------------

/** Clean Laguna program (mach3): in-bed unless `moves` says otherwise. */
function lagunaProgram(moves: readonly string[]): string {
  return ['%', 'G21', 'G90', 'G17', 'M3 S18000', ...moves, 'G0 Z25', 'M5', 'G0 Z25', 'M30', '%'].join('\n')
}

/** Clean Carvera program (smoothieware); `retractZ` = profile workAreaMm.z. */
function carveraProgram(moves: readonly string[], retractZ: number): string {
  return [
    'G21',
    'G90',
    'G17',
    'G54',
    'M3 S15000',
    ...moves,
    `G0 Z${retractZ}`,
    'M5',
    `G0 Z${retractZ}`,
    'M30'
  ].join('\n')
}

/**
 * Realistic OrcaSlicer-flavored K2 output: G91 retraction burst, no M5, no
 * M2/M30, park move far outside any bed once mis-parsed as absolute. The
 * CNC gate would block this THREE ways -- the FDM surface must not.
 */
const ORCA_K2_GCODE = [
  '; generated by OrcaSlicer',
  'G21',
  'G90',
  'M82',
  'G28',
  'G1 Z0.2 F600',
  'G1 X340 Y340 E5 F1500',
  'G91',
  'G1 Z5 E-2 F1200',
  'G90',
  'G1 X9000 Y9000 F9000',
  'M104 S0',
  'M140 S0',
  'M84'
].join('\n')

const fakeIo = (text: string): GateIo => ({ readTextFile: vi.fn().mockResolvedValue(text) })
const failingIo = (msg: string): GateIo => ({
  readTextFile: vi.fn().mockRejectedValue(new Error(msg))
})

