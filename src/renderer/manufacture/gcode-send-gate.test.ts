// === (B) Laguna hard gate with the REAL 1524 x 3048 dims =====================

describe('gateCncProgramForSend -- Laguna Swift 5x10 (1524 x 3048 mm)', () => {
  it('X1600 on the 1524 mm axis is BLOCKING and names the real travel', () => {
    const r = gateCncProgramForSend({
      gcode: lagunaProgram(['G1 X1600 Y100 Z-3 F2000']),
      machine: LAGUNA
    })
    expect(r.allowed).toBe(false)
    const msg = r.blockingErrors.find((e) => e.includes('machine X work area'))
    expect(msg).toBeDefined()
    expect(msg).toContain('1524 mm')
  })
  it('Y3100 on the 3048 mm axis is BLOCKING and names the real travel', () => {
    const r = gateCncProgramForSend({
      gcode: lagunaProgram(['G1 X100 Y3100 Z-3 F2000']),
      machine: LAGUNA
    })
    expect(r.allowed).toBe(false)
    expect(r.blockingErrors.some((e) => e.includes('machine Y work area') && e.includes('3048 mm'))).toBe(true)
  })
  it('a full-sheet program inside 1524 x 3048 is allowed with zero blockers', () => {
    const r = gateCncProgramForSend({
      gcode: lagunaProgram(['G1 X1500 Y3000 Z-3 F2000', 'G1 X10 Y10 F2000']),
      machine: LAGUNA
    })
    expect(r.allowed).toBe(true)
    expect(r.blockingErrors).toEqual([])
  })
})

